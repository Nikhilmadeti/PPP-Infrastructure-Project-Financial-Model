"""Command-line interface: run the model, the scenarios, the Excel export and the hand check.

    python -m ppp_model run        --type toll [--scenario traffic_m20]
    python -m ppp_model scenarios  --type ham
    python -m ppp_model export     --type metro [--out outputs/metro.xlsx]
    python -m ppp_model charts     --type toll        (README §14.3 report charts as PNG in outputs/charts/)
    python -m ppp_model hand-check --type toll        (writes validation/hand_check.xlsx and .md)
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import pandas as pd

from .checks import hand_check
from .export import build_hand_check_workbook, write_workbook
from .inputs import base_config_path, load_yaml
from .model import ModelResults, run_model
from .scenarios import (
    break_even_shortfall,
    load_scenarios,
    profile_comparison,
    run_scenario,
    run_scenarios,
    tornado,
    two_way_table,
)

ROOT = Path(__file__).resolve().parents[2]


def _print(text: str = "") -> None:
    sys.stdout.buffer.write((text + "\n").encode("utf-8"))


def _headline(res: ModelResults) -> str:
    mt = res.metrics
    lines = [
        f"{res.inputs.project.name}",
        f"  TPC {mt.total_project_cost:,.2f} | IDC {mt.idc:,.2f} | debt {mt.debt:,.2f} | equity {mt.equity:,.2f} ₹ Cr",
        f"  min DSCR {mt.min_dscr:.4f}x (op year {mt.min_dscr_op_year}) | avg {mt.avg_dscr:.4f}x | "
        f"LLCR {mt.llcr_cod:.4f}x" if mt.min_dscr is not None else "  no debt service",
        f"  Project IRR {mt.project_irr.display(2)} | Equity IRR {mt.equity_irr.display(2)} | "
        f"NPV {mt.project_npv:,.2f} ₹ Cr | tail {mt.tail_years} years",
    ]
    fails = [c for c in res.checks if c.status == "fail"]
    warns = [c for c in res.checks if c.status == "warn"]
    lines.append(f"  integrity checks: {'ALL PASS' if not fails else f'{len(fails)} FAILED'}; "
                 f"financial warnings: {len(warns)}")
    for c in fails + warns:
        lines.append(f"    [{c.status.upper()}] {c.id} {c.name}: {c.detail}")
    return "\n".join(lines)


def hand_check_markdown(res: ModelResults) -> str:
    rows = hand_check(res)
    n_ok = sum(r.ok for r in rows)
    out = [
        "# Hand check (README §12.3)",
        "",
        f"Generated by `python -m ppp_model hand-check` on {date.today():%d %B %Y} from "
        f"`config/base_{res.inputs.project_type}.yaml` ({res.inputs.project.name}).",
        "",
        "**Method.** Each item below is recomputed from the *inputs* with a scalar, calculator-style formula "
        "(module `ppp_model.checks.hand_check`, which does not call the vectorised model code) and compared with "
        "the model. Where the README procedure allows a model value as a starting point (an opening balance, "
        "losses brought forward, depreciation), the working says *(model value)*. Tolerance: 0.01.",
        "",
        f"**Result: {n_ok} of {len(rows)} items agree within 0.01.**",
        "",
        "Why these years (README §12.3): construction year 2 proves the IDC logic; op year 1 is the first "
        "repayment year with the largest debt, the ramp-up and the minimum DSCR; the first major-maintenance "
        "year shows the DSCR dip; the final repayment year must close the loan at exactly zero.",
        "",
    ]
    section = None
    for r in rows:
        if r.section != section:
            section = r.section
            out += ["", f"## {section}", "", "| Item | Working | Hand value | Model value | Difference | OK? |",
                    "|---|---|---:|---:|---:|:---:|"]
        out.append(f"| {r.item} | `{r.working}` | {r.hand_value:,.4f} | {r.model_value:,.4f} | "
                   f"{r.difference:+.2e} | {'✓' if r.ok else '✗'} |")
    out += ["", "## Hand-check record (README template)", "",
            "| Year | Item | Hand value | Model value | Difference | OK? |", "|---|---|---:|---:|---:|:---:|"]
    picks = [("Construction year 2", "IDC", "C2"), ("Op year 1", "Interest", "Op 1"), ("Op year 1", "Principal", "Op 1"),
             ("Op year 1", "Closing debt", "Op 1"), ("Op year 1", "CFADS", "Op 1"), ("Op year 1", "DSCR", "Op 1")]
    for r in rows:
        if r.section.startswith("Op year") and "major maintenance" in r.section and r.item == "DSCR":
            picks.append((r.section, "DSCR", r.section.split(" (")[0].replace("Op year", "Op")))
        if "final repayment" in r.section and r.item == "Closing debt":
            picks.append((r.section, "Closing debt", r.section.split(" (")[0].replace("Op year", "Op")))
    for section_name, item, label in picks:
        for r in rows:
            if r.section == section_name and r.item == item:
                out.append(f"| {label} | {item} | {r.hand_value:,.4f} | {r.model_value:,.4f} | "
                           f"{r.difference:+.2e} | {'✓' if r.ok else '✗'} |")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m ppp_model", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["run", "scenarios", "export", "charts", "hand-check"])
    parser.add_argument("--type", default="toll", choices=["toll", "metro", "ham"], help="project type")
    parser.add_argument("--config", help="base YAML (default: config/base_<type>.yaml)")
    parser.add_argument("--scenario", default="base", help="scenario key from config/scenarios.yaml")
    parser.add_argument("--out", help="output path for 'export'")
    args = parser.parse_args(argv)

    raw = load_yaml(args.config or base_config_path(args.type))
    config = load_scenarios()
    if args.scenario not in config.scenarios:
        parser.error(f"unknown scenario '{args.scenario}'; choose from {', '.join(config.scenarios)}")
    scenario = config.scenarios[args.scenario]

    if args.command == "run":
        _print(_headline(run_scenario(raw, scenario)))
        return 0
    if args.command == "scenarios":
        table, _ = run_scenarios(raw, config)
        with pd.option_context("display.width", 250, "display.max_columns", 30):
            cols = ["Scenario", "TPC", "Debt", "IDC", "Min DSCR", "Min DSCR op year", "Avg DSCR", "LLCR at COD",
                    "Project IRR", "Equity IRR", "NPV", "Verdict"]
            _print(table[cols].round(4).to_string())
        _print(str(break_even_shortfall(raw, max_shortfall=config.break_even_max_shortfall,
                                        tol=config.break_even_tolerance)))
        return 0
    if args.command == "export":
        res = run_scenario(raw, scenario)
        table, _ = run_scenarios(raw, config)
        two_way = two_way_table(raw, config.two_way_shortfalls, config.two_way_overruns)
        torn = tornado(raw, config.tornado_variables.get(args.type, ()), config.tornado_shock)
        profiles, _ = profile_comparison(raw)
        out = Path(args.out or ROOT / "outputs" / f"ppp_model_{args.type}_{args.scenario}.xlsx")
        write_workbook(res, out, scenario_label=scenario.label, scenario_table=table, two_way=two_way,
                       tornado_df=torn, profile_table=profiles)
        _print(f"Wrote {out}")
        return 0
    if args.command == "charts":
        from .report_charts import write_report_charts  # Matplotlib only needed here

        res = run_scenario(raw, scenario)
        table, _ = run_scenarios(raw, config)
        two_way = two_way_table(raw, config.two_way_shortfalls, config.two_way_overruns)
        torn = tornado(raw, config.tornado_variables.get(args.type, ()), config.tornado_shock)
        _, profile_results = profile_comparison(raw)
        out = Path(args.out or ROOT / "outputs" / "charts" / args.type)
        paths = write_report_charts(res, out, scenario_table=table, two_way=two_way, tornado_df=torn,
                                    profile_results=profile_results)
        _print(f"Wrote {len(paths)} charts to {out}")
        return 0
    res = run_model(raw)
    (ROOT / "validation").mkdir(exist_ok=True)
    xlsx = ROOT / "validation" / "hand_check.xlsx"
    md = ROOT / "validation" / "hand_check.md"
    xlsx.write_bytes(build_hand_check_workbook(res))
    md.write_text(hand_check_markdown(res), encoding="utf-8")
    rows = hand_check(res)
    _print(f"Wrote {xlsx} and {md}: {sum(r.ok for r in rows)} of {len(rows)} items agree within 0.01")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
